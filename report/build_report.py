from pathlib import Path
from tempfile import TemporaryDirectory
from xml.sax.saxutils import escape

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_JUSTIFY, TA_LEFT, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (Image, KeepTogether, PageBreak, Paragraph,
                               SimpleDocTemplate, Spacer, Table, TableStyle)

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/Sarven505/hpp-lattice-gas"
TITLE = "Исследование модели HPP: перераспределение плотности газа и влияние граничных условий"


def build(output: Path):
    summary = json.loads((ROOT / "experiments/summary.json").read_text())
    b = summary["boundaries"]
    config = summary["config"]
    if config != dict(width=128, height=96, steps=800, seeds=12, block=8, p_left=0.45,
                      p_right=0.05, seed_start=2026, threshold=0.1, window=25):
        raise ValueError("Этот текст отчёта относится только к сохранённому эксперименту 128 × 96, 800 шагов, 12 seed.")
    fontdir = Path(matplotlib.get_data_path()) / "fonts/ttf"
    for name, file in [("Body", "DejaVuSerif.ttf"), ("BodyBold", "DejaVuSerif-Bold.ttf"),
                       ("Sans", "DejaVuSans.ttf"), ("SansBold", "DejaVuSans-Bold.ttf"),
                       ("Mono", "DejaVuSansMono.ttf")]:
        pdfmetrics.registerFont(TTFont(name, str(fontdir / file)))
    pdfmetrics.registerFontFamily("Body", normal="Body", bold="BodyBold", italic="Body", boldItalic="BodyBold")
    styles = {
        "body": ParagraphStyle("body", fontName="Body", fontSize=10.5, leading=15,
                               alignment=TA_JUSTIFY, spaceAfter=7),
        "head": ParagraphStyle("head", fontName="SansBold", fontSize=14, leading=19,
                               spaceAfter=12, textColor=colors.HexColor("#244b64")),
        "sub": ParagraphStyle("sub", fontName="SansBold", fontSize=11, leading=15,
                              spaceBefore=7, spaceAfter=7),
        "center": ParagraphStyle("center", fontName="Body", fontSize=11, leading=16,
                                 alignment=TA_CENTER, spaceAfter=5),
        "title": ParagraphStyle("title", fontName="SansBold", fontSize=16, leading=23,
                                alignment=TA_CENTER, spaceAfter=12),
        "small": ParagraphStyle("small", fontName="Sans", fontSize=8, leading=11,
                                spaceAfter=6),
        "caption": ParagraphStyle("caption", fontName="Body", fontSize=9, leading=13,
                                  alignment=TA_LEFT, spaceAfter=12),
        "cell": ParagraphStyle("cell", fontName="Sans", fontSize=8.5, leading=12),
        "code": ParagraphStyle("code", fontName="Mono", fontSize=7.8, leading=11),
        "right": ParagraphStyle("right", fontName="Body", fontSize=10, alignment=TA_RIGHT),
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    story, md = [], [f"# {TITLE}\n", "Растегаев Алексей Эдуардович, СМ6-91.\n",
                     "МГТУ им. Н. Э. Баумана; кафедра СМ6; Компьютерное моделирование.\n",
                     "Преподаватель: Федулов В. А. Москва, 2026.\n", f"Исходный код: {REPO}\n"]
    temporary = TemporaryDirectory()
    tmp = Path(temporary.name)
    eqcounter = 0

    def p(text, style="body"):
        story.append(Paragraph(text, styles[style]))
        md.append(text.replace("<b>", "**").replace("</b>", "**") + "\n")

    def heading(text, newpage=True):
        if newpage: story.append(PageBreak())
        p(text, "head")
        md[-1] = "## " + md[-1]

    def sub(text):
        p(text, "sub"); md[-1] = "### " + md[-1]

    def eq(text, height=12):
        nonlocal eqcounter
        eqcounter += 1
        fig = plt.figure(figsize=(8, height / 25.4), dpi=220)
        fig.text(0.5, 0.5, "$" + text + "$", ha="center", va="center", fontsize=15)
        path = tmp / f"eq{eqcounter}.png"
        fig.savefig(path, transparent=True, bbox_inches="tight", pad_inches=0.08)
        plt.close(fig)
        im = Image(str(path))
        scale = min(145*mm / im.imageWidth, height*mm / im.imageHeight)
        im.drawWidth, im.drawHeight = im.imageWidth*scale, im.imageHeight*scale
        table = Table([[im, Paragraph(f"({eqcounter})", styles["right"])]], colWidths=[154*mm, 12*mm])
        table.setStyle(TableStyle([("VALIGN",(0,0),(-1,-1),"MIDDLE"),
                                   ("BOTTOMPADDING",(0,0),(-1,-1),5)]))
        story.append(table)
        md.append(f"$$ {text} \\quad ({eqcounter}) $$\n")

    def table(caption, data, widths):
        p(caption, "caption")
        cells = [[Paragraph(escape(str(x)), styles["cell"]) for x in row] for row in data]
        t = Table(cells, colWidths=[x*mm for x in widths], repeatRows=1, hAlign="LEFT")
        t.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,0),colors.HexColor("#edf2f6")),
                               ("LINEBELOW",(0,0),(-1,0),0.7,colors.HexColor("#6b8798")),
                               ("LINEBELOW",(0,1),(-1,-1),0.3,colors.HexColor("#d7dfe4")),
                               ("VALIGN",(0,0),(-1,-1),"TOP"),
                               ("TOPPADDING",(0,0),(-1,-1),7),
                               ("BOTTOMPADDING",(0,0),(-1,-1),7)]))
        story.append(t); story.append(Spacer(1,8))
        md.extend(["| " + " | ".join(str(x) for x in row) + " |\n" for row in data[:1]])
        md.append("|" + "---|"*len(data[0]) + "\n")
        md.extend(["| " + " | ".join(str(x) for x in row) + " |\n" for row in data[1:]])

    def figure(name, caption, width=166):
        path = ROOT / "experiments/figures" / name
        im = Image(str(path))
        im.drawHeight = im.imageHeight / im.imageWidth * width*mm
        im.drawWidth = width*mm
        story.append(KeepTogether([im, Spacer(1,5), Paragraph(caption, styles["caption"])]))
        md.extend([f"![{caption}](../experiments/figures/{name})\n"])

    def code(text):
        lines = text.strip().splitlines()
        markup = [escape(line).replace(" ", "&#160;") for line in lines]
        # Colour token spans without changing the code's text or indentation.
        tokens_by_line = {}
        for token in tokenize.generate_tokens(io.StringIO(text.strip()).readline):
            color = None
            if token.type == tokenize.NAME and keyword.iskeyword(token.string): color = "#6f42a1"
            elif token.type == tokenize.STRING: color = "#23734c"
            elif token.type == tokenize.COMMENT: color = "#64748b"
            if color and token.start[0] == token.end[0]:
                tokens_by_line.setdefault(token.start[0]-1, []).append((token.start[1],token.end[1],color))
        formatted = []
        for i, line in enumerate(lines):
            pos, spans = 0, []
            for start,end,color in tokens_by_line.get(i,[]):
                spans += [escape(line[pos:start]).replace(" ", "&#160;"),
                          f'<font color="{color}">{escape(line[start:end]).replace(" ", "&#160;")}</font>']
                pos = end
            spans.append(escape(line[pos:]).replace(" ", "&#160;"))
            formatted.append(Paragraph("".join(spans), styles["code"]))
        t = Table([[line] for line in formatted], colWidths=[166*mm])
        t.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,-1),colors.HexColor("#f5f7fa")),
                              ("TOPPADDING",(0,0),(-1,-1),1), ("BOTTOMPADDING",(0,0),(-1,-1),1)]))
        story.append(KeepTogether([t,Spacer(1,8)]))
        md.append("```python\n" + text.strip() + "\n```\n")

    def fmt(v): return f"{v:.6f}"

    p("Министерство науки и высшего образования Российской Федерации", "center")
    p("Федеральное государственное автономное образовательное учреждение высшего образования", "center")
    p("«Московский государственный технический университет имени Н. Э. Баумана<br/>(национальный исследовательский университет)»", "center")
    story.append(Spacer(1,12*mm))
    p("ФАКУЛЬТЕТ «СПЕЦИАЛЬНОЕ МАШИНОСТРОЕНИЕ»", "center")
    p("КАФЕДРА «РАКЕТНЫЕ И ИМПУЛЬСНЫЕ СИСТЕМЫ» (СМ6)", "center")
    story.append(Spacer(1,20*mm))
    p("ОТЧЁТ ПО ЛАБОРАТОРНОЙ РАБОТЕ", "title")
    p("По дисциплине «Компьютерное моделирование»", "center")
    story.append(Spacer(1,8*mm))
    p(TITLE, "title")
    story.append(Spacer(1,22*mm))
    p("Выполнил: студент группы СМ6-91<br/><b>Растегаев Алексей Эдуардович</b>", "body")
    p("Проверил: <b>Федулов В. А.</b>", "body")
    story.append(Spacer(1,15*mm))
    p("Москва, 2026 г.", "center")

    heading("1. Постановка задачи")
    p(f'Исходный код и данные экспериментов: <link href="{REPO}" color="#246b9d">{REPO}</link>.')
    p("Исследуется модель решётчатого газа HPP D2Q4, предложенная в лекции 4. Выбранная особенность темы - влияние граничных условий на перераспределение первоначально неоднородного газа в прямоугольной области. Сравниваются периодическое замыкание области и отражение от неподвижных стенок.")
    sub("1.1. Цель и измеримые задачи")
    p("<b>Цель:</b> за 800 шагов измерить изменение разности средних плотностей между половинами области, сравнить два типа границ по ансамблю из 12 начальных состояний и проверить точное сохранение массы и корректный баланс импульса.")
    for text in ["1. Формализовать состояния узлов, столкновения, перенос и граничные условия.",
                 "2. Реализовать синхронную модель с управлением через командную строку.",
                 "3. Проверить все локальные состояния, теоретические инварианты и обратимость.",
                 "4. Выполнить парные эксперименты с одинаковыми начальными массивами для двух границ.",
                 "5. Построить карты плотности и скорости; проанализировать динамику и ограничения."]:
        p(text)
    sub("1.2. Допущения и единицы")
    p("Пространство и время дискретны: шаг решётки и длительность такта приняты равными единице. Частицы одинаковы; в каждом направленном канале узла допускается не более одной частицы. Внешние силы, диагональные скорости, температура, случайное рассеяние и добавленное затухание отсутствуют. Случайность используется только для начального заполнения, последующая эволюция детерминирована.")
    p("Плотность измеряется числом частиц на узел, скорость - числом шагов решётки за такт. Физическая калибровка на конкретный газ не выполняется. Требование количественного совпадения с реальным течением в этой работе не ставится.")

    heading("2. Формализация клеточного автомата")
    p("Состояние решётки задаётся булевым массивом n(y, x, i) формы (H, W, 4). Направления i=0,1,2,3 соответствуют востоку, северу, западу и югу; y возрастает вверх на рисунках. Используется окрестность фон Неймана.")
    eq(r"\mathbf{c}_0=(1,0),\quad \mathbf{c}_1=(0,1),\quad \mathbf{c}_2=(-1,0),\quad \mathbf{c}_3=(0,-1)")
    sub("2.1. Столкновение")
    p("В узле ровно две встречные частицы разлетаются по двум перпендикулярным направлениям. При наличии третьей или четвёртой частицы это правило не применяется. Все изменения вычисляются по старому массиву, поэтому обновление синхронно.")
    eq(r"n_i^*=n_i-n_i n_{i+2}(1-n_{i+1})(1-n_{i+3})+(1-n_i)(1-n_{i+2})n_{i+1}n_{i+3}", 15)
    p("В формуле (2) индексы направлений рассматриваются по модулю 4. Астериск обозначает состояние после столкновения, до переноса.")
    table("Таблица 1. Полная классификация 16 локальных состояний", [
        ["Входящие каналы", "Выходящие каналы", "Число вариантов"],
        ["Только восток и запад", "Север и юг", "1"],
        ["Только север и юг", "Восток и запад", "1"],
        ["Пустой узел; одна частица; перпендикулярная пара; три или четыре частицы", "Без изменений", "14"]], [77,65,24])
    sub("2.2. Перенос")
    eq(r"n_i(\mathbf{r}+\mathbf{c}_i,t+1)=n_i^*(\mathbf{r},t)")
    p("При периодических границах координаты назначения берутся по модулю W и H. При выходе за отражающую границу частица остаётся в исходном узле и занимает противоположный канал: восток ↔ запад, север ↔ юг. Отражение занимает один такт; стенка проходит между крайним узлом и внешним пространством.")
    p("Каждый направленный канал имеет ровно одно назначение и один источник. Перенос и отражение являются перестановками каналов: частицы не теряются и не объединяются.")

    heading("3. Наблюдаемые величины и законы сохранения")
    eq(r"\rho(\mathbf{r},t)=\sum_{i=0}^{3}n_i(\mathbf{r},t),\quad \mathbf{j}(\mathbf{r},t)=\sum_{i=0}^{3}n_i(\mathbf{r},t)\mathbf{c}_i")
    eq(r"N(t)=\sum_{\mathbf{r}}\rho(\mathbf{r},t),\quad \mathbf{P}(t)=\sum_{\mathbf{r}}\mathbf{j}(\mathbf{r},t)")
    p("Столкновение меняет только две пары с нулевым суммарным импульсом. Поэтому оно сохраняет массу и импульс в каждом узле. Перенос сохраняет массу глобально; периодические границы сохраняют и глобальный импульс.")
    eq(r"N(t)=N(0),\qquad \mathbf{P}(t)-\mathbf{P}(0)=\sum_{\tau=0}^{t-1}\mathbf{I}_{\mathrm{wall}}(\tau)")
    p("При отражении изменение импульса одной частицы равно -2cᵢ. На каждом шаге подсчитывается импульс от всех отражений. Для периодической области правая часть формулы (6) равна нулю. Балансы вычисляются целочисленно, без допуска на округление.")
    sub("3.1. Пространственное усреднение")
    p("Для карт используются неперекрывающиеся блоки B размером 8 × 8. Сначала суммируются населённости, затем вычисляется скорость, взвешенная по массе:")
    eq(r"\rho_B=\frac{1}{|B|}\sum_{\mathbf{r}\in B}\rho(\mathbf{r}),\qquad \mathbf{u}_B=\frac{\sum_{\mathbf{r}\in B}\mathbf{j}(\mathbf{r})}{\sum_{\mathbf{r}\in B}\rho(\mathbf{r})}")
    p("Если блок пуст, его скорость принимается равной нулю. Усреднение подавляет шум отдельного узла. Даже при нулевом ожидаемом начальном потоке измеренная RMS-скорость не равна нулю из-за конечной выборки частиц.")
    eq(r"\Delta\rho(t)=\overline{\rho}_L(t)-\overline{\rho}_R(t),\quad d(t)=\frac{\Delta\rho(t)}{\Delta\rho(0)}")
    eq(r"CV_\rho=\frac{\mathrm{std}_B(\rho_B)}{\mathrm{mean}_B(\rho_B)},\qquad u_{\mathrm{RMS}}=\sqrt{\frac{1}{K}\sum_{B=1}^{K}|\mathbf{u}_B|^2}")
    p("CV и RMS здесь усредняются равновесно по пространственным блокам. На ансамблевом графике показываются среднее знаковое d(t) и среднее |d(t)|; последнее предотвращает ложное выравнивание из-за взаимного сокращения разных реализаций.")

    heading("4. Реализация и проверка модели")
    p("Программа написана на Python. NumPy выполняет операции над булевыми массивами; Matplotlib строит графики; argparse формирует интерфейс командной строки; pytest выполняет автоматические проверки. Модули динамики, экспериментов, визуализации и интерфейса разделены.")
    sub("4.1. Алгоритм одного шага")
    p("Инициализация → измерение начального состояния → столкновение → подсчёт импульса стенок → перенос → измерение и проверка балансов → сохранение результатов. Цикл повторяется заданное число раз. При ненулевой ошибке баланса расчёт останавливается.")
    p("Листинг 1. Проверка баланса импульса в вычислительном цикле", "caption")
    code('''post_collision = collide(state)
impulse += wall_impulse(post_collision, boundary)
state = stream(post_collision, boundary)
# Баланс импульса с учётом обмена со стенками
error = momentum(state) - momentum0 - impulse
if np.any(error):
    raise RuntimeError("Momentum balance failed")''')
    sub("4.2. Верификация и теоретическая валидация")
    table("Таблица 2. Проверки реализации: 30 тестов пройдены", [
        ["Группа проверок", "Критерий"],
        ["Все 16 локальных состояний", "Правило столкновения; точные масса и импульс; двойное столкновение возвращает исходное состояние"],
        ["Независимая скалярная модель", "Полное совпадение массивов на 15 шагах для каждой границы"],
        ["Обратимость", "100 прямых и 100 обратных шагов возвращают весь исходный массив"],
        ["Одна частица", "Точный период W на торе и 2W между отражающими стенками"],
        ["Поля, начальные условия, ввод", "Взвешенная скорость, пустые блоки, биномиальные характеристики, повторяемость seed, ошибочные параметры"]], [57,109])
    p("Верификация подтверждает соответствие программе правилу HPP. Теоретическая валидация ограничена известными дискретными результатами: инвариантами, обратимостью и движением одной частицы. Экспериментальных данных реального газа для физической валидации не использовано.")

    heading("5. Методика вычислительного эксперимента")
    p("В начальный момент каждый канал заполняется независимо с вероятностью 0.45 в левой половине и 0.05 в правой. Ожидаемые плотности половин равны 1.8 и 0.2; ожидаемая средняя плотность равна 1.0. Ожидаемый глобальный импульс равен нулю, но конкретная конечная выборка может иметь небольшой ненулевой импульс.")
    table("Таблица 3. Параметры серии", [
        ["Параметр", "Значение"], ["Размер поля", "W = 128, H = 96"],
        ["Длительность", "800 шагов; измерение на каждом шаге"],
        ["Ансамбль", "12 seed: 2026-2037; две границы; всего 24 расчёта"],
        ["Начальные вероятности каналов", "pL = 0.45; pR = 0.05"],
        ["Усреднение полей", "Неперекрывающиеся блоки 8 × 8"],
        ["Поздний интервал статистики", "Последние 100 шагов: t = 701-800"],
        ["Критерий временного сближения", "Среднее |d(t)| ≤ 0.1 на 25 последовательных шагах"]], [75,91])
    p("Для каждого seed исходный массив одинаков в двух вариантах границ. Это парный дизайн: различия внутри пары обусловлены границей, а не начальным заполнением. У периодической области есть два стыка между половинами: центральный и через край x=0/W. У отражающей области обмен между половинами возможен только через центральный стык.")
    p("Для поздних показателей сначала берётся среднее за t=701-800 отдельно в каждом расчёте, затем среднее и выборочное стандартное отклонение SD по 12 расчётам. SD характеризует разброс начальных состояний, а не доверительный интервал и не разброс 100 коррелированных временных точек.")
    p("Для снимков поля используется seed=2026. Его фактическое число частиц N=12327 отличается от математического ожидания 12288. Исходный импульс равен (49, -8); начальная разность плотностей составляет 1.600749.")
